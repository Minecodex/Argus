function englishToken(token: string): string {
  return token
    .toLowerCase()
    .replace(/(^|[-_])([a-z])/g, (_, p, c) => (p ? " " : "") + c.toUpperCase());
}
function humanize(code: string, locale: Locale): string {
  if (locale === "zh-CN" && errorSpecialZhMap[code])
    return errorSpecialZhMap[code];
  if (locale === "en-US" && errorSpecialEnMap[code])
    return errorSpecialEnMap[code];
  const tokens = code.split("_");
  if (locale === "en-US")
    return (
      tokens
        .map((token) => errorTokenEnMap[token] ?? englishToken(token))
        .join(" ") + "."
    );
  const text = tokens.map((token) => errorTokenZhMap[token] ?? token).join("");
  return `操作失败：${text}。`;
}

function createCodeMessages(locale: Locale): Record<string, string> {
  return Object.fromEntries(
    ERROR_CODES.map((code) => [code, humanize(code, locale)]),
  );
}

