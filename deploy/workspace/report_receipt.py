"""Bounded, byte-verified receipt for locally generated complete evidence files."""
import hashlib
import json
from pathlib import Path
import re

MAX_RECEIPT_BYTES = 8192
BLOCK = re.compile(r"```json\s*(.*?)\s*```", re.S)


def validate_markdown(conclusion, markdown):
    blocks = BLOCK.findall(markdown)
    expected = json.dumps(conclusion, ensure_ascii=False, indent=2, allow_nan=False).replace("`", "\\u0060")
    if len(blocks) != 1 or blocks[0].strip() != expected:
        raise ValueError("report must contain exactly one complete program-generated evidence JSON block")


def file_info(path, expected):
    path = Path(path)
    digest, size = hashlib.sha256(), 0
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
            size += len(block)
            if size > len(expected):
                raise ValueError("saved report file differs from the generated bytes")
    if size != len(expected) or digest.hexdigest() != hashlib.sha256(expected).hexdigest():
        raise ValueError("saved report file differs from the generated bytes")
    text = str(path)
    return {"path": text if len(text) <= 512 else None, "path_omitted": len(text) > 512,
            "bytes": size, "sha256": digest.hexdigest()}


def create(conclusion, markdown, json_out, markdown_out, source_files):
    validate_markdown(conclusion, markdown)
    encoded = json.dumps(conclusion, ensure_ascii=False, indent=2, allow_nan=False)
    metric = conclusion.get("metric_evidence", conclusion)
    dashboards = conclusion.get("dashboard_evidence", [])
    if not isinstance(metric, dict) or not isinstance(dashboards, list) or len(dashboards) > 8:
        raise ValueError("invalid metric/dashboard evidence shape")
    fields = ("metric", "metric_type", "unit", "unit_origin", "series_count",
              "first_point_at", "last_point_at", "value_min", "value_max", "display_unit",
              "display_transform", "display_min", "display_max", "evaluation_window",
              "input_sha256", "expected_sha256_verified", "query_partial", "limitations")
    summary, omitted = {}, []
    for key in fields:
        value = metric.get(key)
        if isinstance(value, str) and len(value) > 256:
            omitted.append(key)
        else:
            summary[key] = value
    counts = [series["point_count"] for series in metric["series"]]
    summary.update(total_point_count=metric["point_count"], point_count_basis="all_returned_series",
                   min_points_per_series=min(counts), max_points_per_series=max(counts))
    if metric.get("series_count") == 1:
        series = metric["series"][0]
        summary["single_series"] = {k: series[k] for k in ("value_mean", "display_value_mean",
            "first_point_value", "last_point_value", "display_first_point_value", "display_last_point_value")}
    jobs = []
    for dashboard in dashboards:
        states = {}
        for panel in dashboard["panels"]:
            states[panel["status"]] = states.get(panel["status"], 0) + 1
        jobs.append({"job_id": dashboard["job_id"], "attempt_id": dashboard["attempt_id"],
            "complete": dashboard["complete"], "partial": dashboard["partial"],
            "panel_target_count": len(dashboard["panels"]), "panel_status_counts": states})
    result = {
        "schema_version": "argus.evidence_report_receipt/v1", "status": "saved_in_workspace",
        "published": False, "source_files_read": len(source_files),
        "validation": {"single_complete_json_block": True, "json_and_markdown_facts_match": True,
                       "saved_output_bytes_verified": True},
        "json_file": file_info(json_out, (encoded + "\n").encode("utf-8")),
        "markdown_file": file_info(markdown_out, markdown.encode("utf-8")),
        "metric_summary": summary, "omitted_summary_fields": omitted,
        "dashboard_evidence_shape": "array" if dashboards else "absent_no_dashboard_jobs",
        "dashboard_job_count": len(jobs), "dashboard_jobs": jobs,
        "next_step": "Publish the requested Markdown file with the normally searched/described workflow.publish_file. This receipt is not a delivery. Complete evidence and all series/target tables remain in the output files; read them for facts absent from this summary.",
    }
    wire = json.dumps(result, ensure_ascii=False, allow_nan=False)
    if len(wire.encode("utf-8")) > MAX_RECEIPT_BYTES:
        for field in ("json_file", "markdown_file"):
            result[field].update(path=None, path_omitted=True)
        wire = json.dumps(result, ensure_ascii=False, allow_nan=False)
    if len(wire.encode("utf-8")) > MAX_RECEIPT_BYTES:
        raise ValueError("receipt exceeds its bounded output limit; complete files remain available")
    return wire
